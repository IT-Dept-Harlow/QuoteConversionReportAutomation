    /// <summary>
    /// Recursively updates the BackColor and ForeColor of controls within a collection,
    /// applying specific styles for known control types.
    /// </summary>
    /// <param name="controls">The collection of controls to update.</param>
    /// <param name="backColor">The general background color.</param>
    /// <param name="foreColor">The general foreground (text) color.</param>
    /// <param name="buttonBackColor">Specific background color for buttons.</param>
    /// <param name="buttonForeColor">Specific foreground color for buttons.</param>
    /// <param name="textBoxBackColor">Specific background color for text/input boxes.</param>
    /// <param name="textBoxForeColor">Specific foreground color for text/input boxes.</param>
    private void UpdateControlColors(Control.ControlCollection controls, Color backColor, Color foreColor, Color buttonBackColor, Color buttonForeColor, Color textBoxBackColor, Color textBoxForeColor)
    {
        // Iterate through each control in the provided collection
        foreach (Control control in controls)
        {
            // --- Handle specific control types for better theme application ---

            if (control is Button button)
            {
                // For buttons, set specific background/foreground.
                // Set FlatStyle in the designer for best results.
                button.BackColor = buttonBackColor;
                button.ForeColor = buttonForeColor;
                // Optional: Adjust FlatAppearance for Flat buttons
                // button.FlatStyle = FlatStyle.Flat;
                // button.FlatAppearance.BorderColor = foreColor; // Example
            }
            else if (control is TextBox || control is RichTextBox)
            {
                // Apply specific background/foreground for text boxes.
                control.BackColor = textBoxBackColor;
                control.ForeColor = textBoxForeColor;
            }
            else if (control is DateTimePicker dtp)
            {
                // DateTimePicker is difficult to style fully.
                // Set BackColor for the input area, ForeColor for text.
                // Calendar colors are often system-dependent.
                dtp.BackColor = textBoxBackColor;
                dtp.ForeColor = textBoxForeColor;
                // Note: CalendarForeColor/TitleBackColor etc. might have limited effect.
            }
            else if (control is ComboBox comboBox)
            {
                // ComboBoxes need careful styling. Set Back/Fore color.
                // Set FlatStyle in the designer for best results.
                comboBox.BackColor = textBoxBackColor;
                comboBox.ForeColor = textBoxForeColor;
                // comboBox.FlatStyle = FlatStyle.Flat; // Set in designer
                // Note: Dropdown list styling is mostly controlled by the OS.
            }
            else if (control is CheckBox checkbox)
            {
                // Checkboxes often look best inheriting the container's background.
                // Set the ForeColor for the text. Make BackColor transparent or match container.
                checkbox.BackColor = Color.Transparent; // Use Transparent for checkboxes
                checkbox.ForeColor = foreColor;
            }
            else if (control is Label label)
            {
                // Labels should typically have a transparent background unless specifically designed otherwise.
                // Check if it's the special label6 before making transparent
                if (label.Name == "label6")
                {
                    // Keep label6 background matching the form, set text color
                    label.BackColor = backColor; // Match form background
                    label.ForeColor = foreColor;
                }
                else
                {
                    // Make other labels transparent
                    label.BackColor = Color.Transparent;
                    label.ForeColor = foreColor;
                }
            }
            else if (control is GroupBox groupBox)
            {
                // Apply general ForeColor to the GroupBox text (border). Background usually inherited.
                groupBox.ForeColor = foreColor;
                // Recursively apply themes to controls *inside* the GroupBox
                UpdateControlColors(groupBox.Controls, backColor, foreColor, buttonBackColor, buttonForeColor, textBoxBackColor, textBoxForeColor);
            }
            else if (control is Panel panel) // Apply to Panels too
            {
                // Panels often act as containers, match the main background.
                panel.BackColor = backColor;
                // Recursively apply themes to controls *inside* the Panel
                UpdateControlColors(panel.Controls, backColor, foreColor, buttonBackColor, buttonForeColor, textBoxBackColor, textBoxForeColor);
            }
            else if (control is StatusStrip || control is ToolStrip) // Skip toolstrips/statusstrips
            {
                // These are handled separately in ApplyTheme or require custom renderers.
                continue;
            }
            else // Default for other/unknown controls
            {
                // Apply general back/fore colors. Might need adjustment for custom controls.
                try
                {
                    control.BackColor = backColor;
                    control.ForeColor = foreColor;
                }
                catch (Exception ex)
                {
                    // Log if setting color fails for an unexpected control type
                    Logger.LogWarning($"Could not set theme colors for control '{control.Name}' of type {control.GetType().Name}: {ex.Message}");
                }
            }
        }
    }

