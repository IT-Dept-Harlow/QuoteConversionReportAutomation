    /// Validates if the selected date range falls within the selected Financial Year,
    /// but only if the Financial Year dropdown is currently visible (for Daily/Weekly reports).
    /// Prompts the user to confirm if there's a mismatch.
    /// </summary>
    /// <returns>True if validation passes, is not applicable, or the user confirms to proceed despite mismatch. False if the user cancels due to mismatch.</returns>
    private bool ValidateFinancialYearSelection()
    {
        // Only perform validation if the FY dropdown is visible and has a selected item
        if (finYearDropBox.Visible && finYearDropBox.SelectedItem != null)
        {
            string selectedFinYear = finYearDropBox.SelectedItem.ToString()!;
            // Use the static validation method from ExcelCopyData helper class
            if (!ExcelCopyData.IsFinancialYearValid(selectedFinYear, datepickFrom.Value, datepickTo.Value))
            {
                // Log the potential mismatch and prompt the user
                Logger.LogWarning($"Potential FY mismatch: Selected FY '{selectedFinYear}', Date Range '{datepickFrom.Value:d}' to '{datepickTo.Value:d}'. Prompting user.");
                DialogResult dr = MessageBox.Show(
                    $"The selected date range ({datepickFrom.Value:d} - {datepickTo.Value:d}) does not fall entirely within the selected Financial Year ({selectedFinYear}).\n\n" +
                    "Do you want to continue anyway?",
                    "Financial Year Mismatch Warning",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Warning);

                // If user clicks No, validation fails
                if (dr == DialogResult.No)
                {
                    Logger.LogInfo("User chose not to proceed due to FY mismatch.");
                    return false; // Indicate validation failure / cancellation
                }
                // If user clicks Yes, log it and allow proceeding
                Logger.LogWarning("User chose to proceed despite FY mismatch warning.");
            }
        }
        // Validation passed, or was not applicable (FY dropdown hidden)
        return true;
    }

    // --- File Handling Helper ---

    /// <summary>
    /// Opens the specified file using the default system application associated with its extension.
    /// Handles potential errors like file not found or no associated application.
    /// </summary>
    /// <param name="filePath">The full path to the file to open.</param>
    /// <param name="fileTypeDescription">A user-friendly description of the file type (e.g., "raw report output", "processed analysis file") for logging and error messages.</param>
    private void OpenFileHelper(string filePath, string fileTypeDescription)
    {
        Logger.LogInfo($"Attempting to open {fileTypeDescription}: {filePath}");
        try
        {
            // Check if file exists before attempting to open
            if (!File.Exists(filePath))
            {
                Logger.LogWarning($"{Capitalize(fileTypeDescription)} file not found at path: {filePath}");
                MessageBox.Show($"{Capitalize(fileTypeDescription)} file was not found:\n{filePath}", "File Not Found", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }
            // Use Process.Start with UseShellExecute=true to leverage Windows file associations
            Process.Start(new ProcessStartInfo(filePath) { UseShellExecute = true });
            Logger.LogInfo($"Successfully initiated opening of {fileTypeDescription} file.");
        }
        catch (Exception ex) // Catch errors during Process.Start (e.g., no application associated, permissions)
        {
            Logger.LogError($"Error opening {fileTypeDescription} file '{filePath}': {ex}");
            MessageBox.Show($"Could not open the {fileTypeDescription} file.\nError: {ex.Message}", "File Open Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
        }
    }

