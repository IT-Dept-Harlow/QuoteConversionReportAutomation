    /// <summary>
    /// Populates the Financial Year dropdown (finYearDropBox) with the current
    /// and previous financial years based on the value initialized during Form Load.
    /// Selects the current financial year by default.
    /// </summary>
    private void PopulateFinancialYearDropdown()
    {
        // Use SafeControlUpdate as this modifies UI controls
        SafeControlUpdate(finYearDropBox, () =>
        {
            finYearDropBox.Items.Clear(); // Clear existing items
            string currentFY = _financialYear; // Use the FY string calculated during Form_Load

            if (!string.IsNullOrEmpty(currentFY))
            {
                // Add the current FY
                finYearDropBox.Items.Add(currentFY);
                // Calculate and add the previous FY using the helper method
                string? previousFY = ExcelCopyData.GetPreviousFinancialYear(currentFY);
                if (!string.IsNullOrEmpty(previousFY))
                {
                    finYearDropBox.Items.Add(previousFY);
                }
            }
            else // Handle case where FY calculation failed during load
            {
                Logger.LogWarning("Could not determine current financial year for dropdown population.");
                finYearDropBox.Items.Add("FY Unknown"); // Add placeholder
            }

            // Select the first item (usually the current FY) if items were added
            if (finYearDropBox.Items.Count > 0)
            {
                finYearDropBox.SelectedIndex = 0;
            }
        });
    }

