    /// <summary>
    /// Calculates the date range for the Monthly report type.
    /// If run on or before the 15th, it returns the previous full month.
    /// If run after the 15th, it returns the current month from the 1st to today.
    /// Financial Year dropdown is hidden for this type.
    /// </summary>
    /// <param name="today">The current date.</param>
    /// <returns>A tuple containing the start date, end date, and a boolean indicating FY visibility (always false).</returns>
    private static (DateTime DateFrom, DateTime DateTo, bool ShowFinYear) CalculateMonthlyRange(DateTime today)
    {
        DateTime dateFrom, dateTo;
        if (today.Day <= 15)
        {
            // Previous full month
            DateTime firstDayOfCurrentMonth = new DateTime(today.Year, today.Month, 1);
            dateTo = firstDayOfCurrentMonth.AddDays(-1);   // Last day of previous month
            dateFrom = dateTo.AddDays(1).AddMonths(-1); // First day of previous month
        }
        else
        {
            // Current month period (1st to today)
            dateFrom = new DateTime(today.Year, today.Month, 1); // First day of current month
            dateTo = today;                                     // Today's date
        }
        return (dateFrom, dateTo, false); // Hide FY dropdown for Monthly
    }

    /// <summary>
    /// Calculates the date range for the Quarterly report type.
    /// Returns the previous full calendar quarter relative to the current date.
    /// Financial Year dropdown is hidden for this type.
    /// </summary>
    /// <param name="today">The current date.</param>
    /// <returns>A tuple containing the start date, end date, and a boolean indicating FY visibility (always false).</returns>
    private static (DateTime DateFrom, DateTime DateTo, bool ShowFinYear) CalculateQuarterlyRange(DateTime today)
    {
        // Determine current quarter (1-4)
        int currentQuarter = (today.Month - 1) / 3 + 1;
        // Calculate the first day of the current quarter
        DateTime firstDayOfCurrentQuarter = new DateTime(today.Year, (currentQuarter - 1) * 3 + 1, 1);
        // The last day of the previous quarter is the day before the first day of the current quarter
        DateTime dateTo = firstDayOfCurrentQuarter.AddDays(-1);
        // The first day of the previous quarter is 3 months before the first day of the current quarter
        DateTime dateFrom = firstDayOfCurrentQuarter.AddMonths(-3);
        return (dateFrom, dateTo, false); // Hide FY dropdown for Quarterly
    }

    // --- String Helpers ---

    /// <summary>
    /// Capitalizes the first letter of a string.
    /// </summary>
    /// <param name="text">The input string.</param>
    /// <returns>The string with the first letter capitalized, or the original string if null or empty.</returns>
    private static string Capitalize(string text)
    {
        return string.IsNullOrEmpty(text) ? text : char.ToUpperInvariant(text[0]) + text[1..];
    }

    /// <summary>
    /// Gets the quarter number (Q1, Q2, Q3, Q4) for a given date.
    /// </summary>
    /// <param name="date">The date.</param>
    /// <returns>A string representing the quarter (e.g., "Q1").</returns>
    private static string GetQuarterString(DateTime date)
    {
        return $"Q{(date.Month - 1) / 3 + 1}";
    }

