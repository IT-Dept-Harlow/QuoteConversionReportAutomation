        // Apply to Form itself
        this.BackColor = backColor;
        this.ForeColor = foreColor; // Sets default text color for controls inheriting from form

        // Apply colors to child controls recursively/selectively
        UpdateControlColors(this.Controls, backColor, foreColor, buttonBackColor, buttonForeColor, textBoxBackColor, textBoxForeColor);

